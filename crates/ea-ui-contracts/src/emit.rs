/// Die vollstaendige TypeScript-Kontraktdatei als Zeichenkette.
///
/// Zwei Aufrufe liefern byteidentische Ergebnisse; das ist zugesichert und
/// nicht bloss beobachtet (`tests/generated_ts_is_current.rs`).
#[must_use]
pub fn emit_typescript() -> String {
    let mut emitted = String::from(HEADER);

    emitted.push_str("\n// The closed unions of the contract surface.\n");
    for (name, literals) in closed_unions() {
        push_union(&mut emitted, name, literals);
    }

    emitted.push_str("\n// The Writer view models.\n");
    for (name, fields) in VIEW_MODELS_V1 {
        push_object(&mut emitted, name, fields);
    }

    emitted.push_str("\n// The value arrays, so that no consumer repeats a literal.\n");
    for (name, literals) in closed_unions() {
        push_values(&mut emitted, name, literals);
    }

    emitted
}

/// Die vollstaendige TypeScript-Kontraktdatei des READERS als Zeichenkette.
///
/// Derselbe Kopf, dieselbe Determinismuszusage, dieselben Formregeln — eine
/// ANDERE Menge Vereinigungen. ZWEI Ausdruecke statt einer Datei mit beidem,
/// weil `apps/desktop/src/bridge/no-hand-written-contracts.test.ts` jedes
/// Literal JEDER emittierten Vereinigung aus jeder handgeschriebenen
/// Desktop-Quelle verbannt: `ungueltig`, `vorhanden` oder `ausstehend` dort
/// einzutragen verengte die Writer-Flaeche ohne Reader-Grund.
///
/// Zwei Aufrufe liefern byteidentische Ergebnisse; das ist zugesichert und
/// nicht bloss beobachtet (`tests/generated_ts_is_current.rs`).
#[must_use]
pub fn emit_reader_typescript() -> String {
    let mut emitted = String::from(HEADER);

    emitted.push_str("\n// The closed unions of the contract surface.\n");
    for (name, literals) in crate::READER_ENUMS_V1 {
        push_union(&mut emitted, name, literals);
    }

    emitted.push_str("\n// The view models of the reader surface.\n");
    for (name, fields) in READER_VIEW_MODELS_V1 {
        push_object(&mut emitted, name, fields);
    }

    emitted.push_str("\n// The value arrays, so that no consumer repeats a literal.\n");
    for (name, literals) in crate::READER_ENUMS_V1 {
        push_values(&mut emitted, name, literals);
    }

    emitted
}

/// Jede emittierte Vereinigung, in fester Reihenfolge: erst die
/// Sicherheitsaufzaehlungen, dann die uebrigen geschlossenen Mengen.
fn closed_unions() -> impl Iterator<Item = &'static (&'static str, &'static [&'static str])> {
    crate::SECURITY_ENUMS_V1
        .iter()
        .chain(crate::WRITER_ENUMS_V1)
}

fn push_union(emitted: &mut String, name: &str, literals: &[&str]) {
    emitted.push_str("\nexport type ");
    emitted.push_str(name);
    emitted.push_str(" =\n");
    for literal in literals {
        emitted.push_str("  | '");
        emitted.push_str(literal);
        emitted.push_str("'\n");
    }
}

fn push_object(emitted: &mut String, name: &str, fields: &[(&str, &str)]) {
    emitted.push_str("\nexport type ");
    emitted.push_str(name);
    emitted.push_str(" = {\n");
    for (field, declared_type) in fields {
        emitted.push_str("  readonly ");
        emitted.push_str(field);
        emitted.push_str(": ");
        emitted.push_str(declared_type);
        emitted.push('\n');
    }
    emitted.push_str("}\n");
}

fn push_values(emitted: &mut String, name: &str, literals: &[&str]) {
    emitted.push_str("\nexport const ");
    emitted.push_str(&screaming_snake(name));
    emitted.push_str("_VALUES = [\n");
    for literal in literals {
        emitted.push_str("  '");
        emitted.push_str(literal);
        emitted.push_str("',\n");
    }
    emitted.push_str("] as const\n");
}

/// `LocalAuditOutcomeV1` wird zu `LOCAL_AUDIT_OUTCOME_V1`.
fn screaming_snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    let mut previous_is_lower_or_digit = false;
    for character in name.chars() {
        if character.is_ascii_uppercase() && previous_is_lower_or_digit {
            out.push('_');
        }
        previous_is_lower_or_digit = character.is_ascii_lowercase() || character.is_ascii_digit();
        out.push(character.to_ascii_uppercase());
    }
    out
}
