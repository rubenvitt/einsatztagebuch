//! Der Emitter: EINE Zeichenkette, deterministisch, nur Deklarationen.
//!
//! Vier Quellen eines Byteunterschieds zwischen zwei Laeufen sind bekannt, und
//! keine davon existiert hier: die Reihenfolge kommt aus deklarierten Listen
//! und niemals aus einer `HashMap`, nichts formatiert einen Zeitstempel,
//! nichts liest einen Pfad und nichts liest eine Version aus der Umgebung.
//!
//! Die Ausgabe ist **deklarationsfrei von Berechnung**: ein fester
//! Kopfkommentar, `export type`-Vereinigungen, `export type`-Objekttypen und
//! `export const … as const`-Arrays. Keine Funktion, kein Pfeil, keine Klasse,
//! kein Import. `\n` als Zeilenende, zwei Leerzeichen Einrueckung, eine
//! abschliessende Zeilenschaltung.

